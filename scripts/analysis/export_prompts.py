"""
Write the system-prompts appendix of the paper straight from src/utils/system_prompts.py.

The appendix must show the prompts the runs actually used, so it is generated from the same constants the eval scripts
import rather than copied by hand. Re-run after any change to a prompt:

    python scripts/analysis/export_prompts.py       # writes paper/appendices/sec_prompts.tex

Two kinds of character cannot go into a pdfLaTeX `lstlisting` as raw UTF-8: the em dash, and the Chinese example
sentence in the UniversalNER prompts. Both are passed through the listing's escape delimiters -- the dash as
\\textemdash, the Chinese inside a CJK environment (CJKutf8, loaded in main.tex) -- so the prompt is printed exactly.
Placeholders such as {question} are shown as they appear in the code; they are filled per example at run time.
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "paper" / "appendices" / "sec_prompts.tex"
sys.path.insert(0, str(REPO / "src"))

import utils.system_prompts as P  # noqa: E402

# (dataset, tagging prompt, context-based prompt) -- the constants imported by the eval scripts of each dataset.
DATASETS = [
    ("CoNLL-2003",   "CONSTR_GEN",                  "CONTEXT_BASE_CONLL"),
    ("UniversalNER", "CONSTR_GEN_UNER",             "CONTEXT_BASE_UNER"),
    ("Toxic Spans",  "CONSTR_GEN_TOXIC_SPANS",      "CONTEXT_BASE_TOXIC_SPANS"),
    ("LegalQAEval",  "CONSTR_GEN_LEGALQA_TEMPLATE", "CONTEXT_BASE_LEGALQA_TEMPLATE"),
    ("ESA-MT",       "CONSTR_GEN_WMT_TEMPLATE",     "CONTEXT_BASE_WMT_TEMPLATE"),
    ("MultiGEC",     "CONSTR_GEN_MULTIGEC",         "CONTEXT_BASE_MULTIGEC"),
]

ESC_OPEN, ESC_CLOSE = "(*@", "@*)"
CJK_RUN = re.compile(r"[　-〿一-鿿＀-￯]+")


def escape(text):
    """Route the characters pdfLaTeX listings cannot take through the escape delimiters."""
    if ESC_OPEN in text or ESC_CLOSE in text:
        raise SystemExit("a prompt contains the listings escape delimiter -- pick another one")
    text = CJK_RUN.sub(lambda m: f"{ESC_OPEN}\\begin{{CJK}}{{UTF8}}{{gbsn}}{m.group(0)}\\end{{CJK}}{ESC_CLOSE}", text)
    text = text.replace("—", f"{ESC_OPEN}\\textemdash{{}}{ESC_CLOSE}")
    leftover = sorted({c for c in CJK_RUN.sub("", text) if ord(c) > 126})
    if leftover:
        raise SystemExit(f"unhandled non-ASCII characters in a prompt: {leftover}")
    return text


def listing(dataset, kind, constant):
    body = escape(getattr(P, "SYSTEM_PROMPT_" + constant).strip("\n"))
    return (f"\\begin{{lstlisting}}[caption={{{dataset}, {kind}}}]\n{body}\n\\end{{lstlisting}}\n")


def main():
    parts = [
        "% GENERATED by scripts/analysis/export_prompts.py from src/utils/system_prompts.py -- do not edit by hand.\n",
        "\\section{System Prompts}\n\\label{app:prompts}\n\n",
        "The system prompts used in all experiments, exactly as in the code. Each context-based prompt keeps the task "
        "description and label definitions of the tagging prompt for the same dataset and replaces the inline-markup "
        "output format with a JSON list of spans with context. Placeholders in braces are filled per example.\n\n",
        "\\lstset{basicstyle=\\ttfamily\\scriptsize, breaklines=true, columns=fullflexible, keepspaces=true, "
        f"frame=single, framesep=2pt, xleftmargin=3pt, xrightmargin=3pt, captionpos=t, escapeinside={{{ESC_OPEN}}}{{{ESC_CLOSE}}}}}\n\n",
        "\\subsection*{Constrained and unconstrained tagging}\n\n",
    ]
    parts += [listing(d, "tagging", t) for d, t, _ in DATASETS]
    parts.append("\n\\subsection*{Context-based prompting}\n\n")
    parts += [listing(d, "context-based", c) for d, _, c in DATASETS]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({sum(len(getattr(P, 'SYSTEM_PROMPT_' + n).split()) for d in DATASETS for n in d[1:])} prompt words)")


if __name__ == "__main__":
    main()
